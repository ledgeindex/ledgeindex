#!/usr/bin/env node
/**
 * Bundle the desktop server into a single CJS file.
 *
 * Why CJS and not ESM: the dependency graph is full of CommonJS packages that
 * call require() on node builtins. In an ESM bundle every one of those needs a
 * createRequire shim, and external CJS packages lose their named exports to
 * interop. CJS output makes both problems disappear.
 *
 * Output (into the staged runtime dir):
 *   server.cjs — the bundle, exports the worker + standalone surface
 *   start.cjs  — launcher for smoke tests and manual debugging
 */
import { writeFileSync } from "node:fs";
import { builtinModules } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { BUNDLE_EXTERNALS } from "./desktop-server-externals.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const entry = join(root, "hosts", "desktop-server", "src", "worker-runtime.ts");

export const BUNDLE_FILE = "server.cjs";
export const START_FILE = "start.cjs";

function log(...args) {
  console.log("[bundle-desktop-server]", ...args);
}

const BUILTINS = new Set(builtinModules);

/** "@libsql/client/node" → "@libsql/client", "jsdom" → "jsdom" */
function packageNameOf(specifier) {
  const parts = specifier.split("/");
  return specifier.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
}

/**
 * The package names the bundle actually requires at runtime, read back from the
 * build. A hand-written list cannot serve this: BUNDLE_EXTERNALS holds wildcards
 * like `@libsql/*`, and expanding those by walking dependencies misses packages
 * that sit *above* a native binding in the graph — @libsql/client depends on
 * libsql, not the reverse, so nothing would reach it and the packaged app died
 * with "Cannot find module '@libsql/client'".
 *
 * @param {import('esbuild').Metafile} metafile
 * @returns {string[]}
 */
function externalPackagesFrom(metafile) {
  const names = new Set();
  for (const output of Object.values(metafile.outputs)) {
    for (const imported of output.imports ?? []) {
      if (!imported.external) continue;
      const path = imported.path;
      if (path.startsWith("node:") || path.startsWith(".")) continue;
      const name = packageNameOf(path);
      if (!BUILTINS.has(name)) names.add(name);
    }
  }
  return [...names].sort();
}

/**
 * @param {string} destDir staged runtime dir (apps/desktop/build/desktop-server)
 * @returns {Promise<{ bytes: number, externals: string[] }>}
 */
export async function bundleDesktopServer(destDir) {
  const outfile = join(destDir, BUNDLE_FILE);

  const result = await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node22",
    // Electron's Node is the only consumer, so keep the bundle debuggable.
    minify: false,
    sourcemap: false,
    external: BUNDLE_EXTERNALS,
    logLevel: "warning",
    metafile: true,
  });

  writeFileSync(
    join(destDir, START_FILE),
    [
      "// Generated by scripts/bundle-desktop-server.mjs",
      `require("./${BUNDLE_FILE}").startStandalone().catch((error) => {`,
      '  console.error("[desktop-server] failed to start", error);',
      "  process.exit(1);",
      "});",
      "",
    ].join("\n"),
  );

  const externals = externalPackagesFrom(result.metafile);

  const bytes = Object.values(result.metafile.outputs).find(
    (out) => out.entryPoint,
  )?.bytes;
  const mb = bytes ? (bytes / (1024 * 1024)).toFixed(1) : "?";
  log(`bundled ${relative(root, outfile)} (${mb} MB)`);
  log(`requires ${externals.length} external packages: ${externals.join(", ")}`);

  return { bytes: bytes ?? 0, externals };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const destDir =
    process.argv[2] ?? join(root, "apps", "desktop", "build", "desktop-server");
  await bundleDesktopServer(destDir);
}
